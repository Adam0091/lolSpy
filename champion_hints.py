def item_abstract_hint(tags: list | None, price: int | None = None) -> str:
    tags = tags or []
    for tag in tags:
        if tag in ITEM_TAG_HINTS:
            return ITEM_TAG_HINTS[tag]
    if isinstance(price, int):
        if price >= 3000:
            return "Покупка для тех, кто дожил до развязки"
        if price >= 1500:
            return "Шаг в середину пути"
        if price > 0:
            return "Скромное начало большой силы"
    return "Вещь с тихим назначением"
