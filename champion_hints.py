def skin_line_hint(skin_name: str | None) -> str | None:
    if not skin_name:
        return None
    lower = skin_name.casefold()
    for needle, hint in SKIN_LINE_HINTS:
        if needle.casefold() in lower:
            return hint
    return "Образ из другой истории, не из повседневности"


